    private void configurarAcoes() {
        btnCancelar.addActionListener(e -> {
            TelaLogin login = new TelaLogin();
            login.setVisible(true);
            dispose();
        });
        
        btnSalvar.addActionListener(e -> cadastrarUsuario());
    }
    
    private void cadastrarUsuario() {
        String nome = txtFieldNome.getText();
        String email = txtFieldEmail.getText();
        String senha = txtFieldSenha.getText();
        String perfil = comboBoxUserAdmin.getSelectedItem().toString();
        
        if (nome.isEmpty() || nome.equals("Insira seu nome...")) {
            javax.swing.JOptionPane.showMessageDialog(null, "Informe o nome de usuário.");
            return;
        }
        
        if (email.isEmpty() || email.equals("Insira seu e-mail...")) {
            javax.swing.JOptionPane.showMessageDialog(null, "Informe o e-mail do usuário.");
            return;
        }
        
        if (senha.isEmpty() || senha.equals("Insira sua senha...")) {
            javax.swing.JOptionPane.showMessageDialog(null, "Informe a senha do usuário.");
            return;
        }
        
        Usuario usuario = new Usuario(nome, email, senha, perfil);
        
        UsuarioDAO dao = new UsuarioDAO();
        dao.salvar(usuario);
        
        javax.swing.JOptionPane.showMessageDialog(null, "Usuário cadastrado com sucesso!");
        
        TelaLogin login = new TelaLogin();
        login.setVisible(true);
        dispose();
    }

